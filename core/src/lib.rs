//! Движок нагрузки GamingCpuV1.
//!
//! Воспроизводимо моделирует структуру CPU-зависимой соревновательной игры:
//! последовательная «главная» работа потока, ограниченный набор параллельных
//! задач воркерам, синхронизация, детерминированное объединение результатов.
//! Один завершённый проход этой цепочки = один тик.
//!
//! Модуль `alloc_count` — считающий глобальный аллокатор: он устанавливается
//! в тестовой сборке этого крейта и в бинаре консольного валидатора, чтобы
//! проверять «0 аллокаций в главном цикле тиков» извне.

pub mod alloc_count;
