// Каркас страницы: обёртка колонки и шапка.
//
// Раньше каждый экран собирал свой корневой div и свою шапку руками, и
// результат разъезжался при переключении вкладок:
//
//   — «Бенчмарк» рисовал заголовок в `.wizard-header` без верхнего отступа,
//     остальные четыре — в `.page-head` с отступом 4 px, поэтому H1 стоял на
//     4 px выше;
//   — вес и межбуквенный интервал заголовка тоже были разными (700 / −0.3 px
//     против 650 / −0.2 px);
//   — у «Бенчмарка» под шапкой была линия и отступ 20 px, у остальных —
//     ничего, и следующий блок вставал на другой высоте;
//   — вертикальный ритм блоков задавался на странице: `--sp-4` по умолчанию,
//     `--sp-3` на «Результатах», `--sp-2` на «Настройках»;
//   — короткая страница центрировалась по вертикали, длинная прижималась к
//     верху, поэтому один и тот же экран прыгал на треть высоты при смене
//     вкладки.
//
// Здесь обе части макета: `Page` даёт колонку с единым ритмом, `PageHead` —
// шапку с заголовком на одном и том же расстоянии от верхнего края рабочей
// области. Стили и цвет берутся из токенов, здесь только порядок блоков.

import type { ReactNode } from "react";
import { useCascade } from "./useCascade";

/**
 * Колонка страницы.
 *
 * `active` включает каскад появления: класс перезапускается при каждом показе,
 * иначе после возврата на вкладку экран выходил бы «мёртвым» (см.
 * `useCascade`).
 *
 * `fill` — для экранов с собственной прокруткой внутри колонки («Логи»,
 * «Результаты»): им нужна вся высота, а не только своё содержимое.
 */
export function Page({
  active,
  fill = false,
  className = "",
  children,
}: {
  active: boolean;
  fill?: boolean;
  className?: string;
  children: ReactNode;
}) {
  const ref = useCascade<HTMLDivElement>(active);
  const cls = ["page", fill ? "fill" : "", className].filter(Boolean).join(" ");
  return (
    <div ref={ref} className={cls}>
      {children}
    </div>
  );
}

/**
 * Шапка страницы: заголовок, необязательная сводка и действия справа.
 *
 * Порядок блоков фиксирован здесь, а не в разметке страницы: заголовок,
 * потом `meta` (сводка или этапы мастера), потом действия. Иначе «Бенчмарк» со
 * своим степпером снова отделился бы от остальных экранов.
 */
export function PageHead({
  title,
  sub,
  actions,
  children,
}: {
  title: string;
  /** Сводка рядом с заголовком: счётчик, объём, состав. */
  sub?: ReactNode;
  /** Кнопки справа. */
  actions?: ReactNode;
  /** Слот между заголовком и действиями: этапы мастера на «Бенчмарке». */
  children?: ReactNode;
}) {
  return (
    <div className="page-head">
      <h1>{title}</h1>
      {sub ? <span className="sub">{sub}</span> : null}
      {children}
      {actions ? <div className="actions">{actions}</div> : null}
    </div>
  );
}